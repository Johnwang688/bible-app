// Generates the Memory section's speech tables (client/src/memory/speech/data/*.ts).
// Run: node scripts/gen-speech-tables.cjs <path to a checkout with node_modules containing
//      pinyin-pro, to-jyutping and opencc-js> (Little Lamb's bible-memory-app works).
// The tables replace those three packages at runtime: one toneless reading per character,
// keyed after the traditional -> simplified normalisation. See speech/tableKeyer.ts.
/* eslint-disable */
const fs = require('fs');
const path = require('path');

const SRC = process.argv[2];
if (!SRC) throw new Error('usage: node scripts/gen-speech-tables.cjs <dir with node_modules>');
const req = (p) => require(path.join(SRC, 'node_modules', p));
const { pinyin } = req('pinyin-pro');
const { getJyutpingList } = req('to-jyutping');
const OpenCC = req('opencc-js/dist/umd/t2cn.js');
const versions = ['pinyin-pro', 'to-jyutping', 'opencc-js']
  .map((p) => `${p} ${req(`${p}/package.json`).version}`)
  .join(', ');

const han = (ch) => /\p{Script=Han}/u.test(ch);
const set = new Set();
const decode = (enc, hiLo, hiHi, loLo, loHi) => {
  const d = new TextDecoder(enc);
  for (let h = hiLo; h <= hiHi; h++)
    for (let l = loLo; l <= loHi; l++) {
      const s = d.decode(Uint8Array.from([h, l]));
      if (Array.from(s).length === 1 && han(s)) set.add(s);
    }
};
decode('gbk', 0xb0, 0xf7, 0xa1, 0xfe); // GB2312 hanzi
decode('big5', 0xa4, 0xf9, 0x40, 0x7e); // Big5 common + less common
decode('big5', 0xa4, 0xf9, 0xa1, 0xfe);
// Cantonese colloquial characters Whisper's 'yue' output uses.
for (const ch of '嘅係唔佢冇咗嘢啲哋喺乜嚟噉咁啱嗰咩嘞喇囉吖嘛揾搵睇攞俾畀嚿佬仔乸冚瞓') set.add(ch);
// Every character in the TMS library.
const lib = fs.readFileSync(path.join(__dirname, '../src/memory/library/tms.ts'), 'utf8');
for (const ch of lib) if (han(ch)) set.add(ch);

const convert = OpenCC.Converter({ from: 'hk', to: 'cn' });
// Same per-character overrides as Little Lamb's speech/normalize.ts.
const OVERRIDES = { 著: '着', 藉: '借' };
const t2s = {};
for (const ch of [...set].sort()) {
  const c = OVERRIDES[ch] ?? convert(ch);
  if (Array.from(c).length === 1 && c !== ch) t2s[ch] = c;
}
const simplified = new Set([...set].map((ch) => t2s[ch] ?? ch));

// Single-character readings, except where the contextual reading Scripture uses dominates.
const MANDARIN_PREFER = { 了: 'le', 的: 'de', 地: 'di', 得: 'de', 着: 'zhe', 么: 'me' };
const group = (fn) => {
  const out = {};
  for (const ch of [...simplified].sort()) {
    const r = fn(ch);
    if (!r || r === ch) continue;
    (out[r] ??= []).push(ch);
  }
  return Object.fromEntries(Object.entries(out).sort().map(([k, v]) => [k, v.join('')]));
};
const mandarin = group((ch) => MANDARIN_PREFER[ch] ?? pinyin(ch, { toneType: 'none' }));
const cantonese = group((ch) => {
  const [[, jp]] = getJyutpingList(ch);
  return jp ? jp.replace(/[1-6]$/, '') : null;
});

const header = (what) =>
  `// GENERATED by client/scripts/gen-speech-tables.cjs from ${versions}. Do not edit.\n` +
  `// ${what}\n// pinyin-pro: MIT. to-jyutping: BSD-2-Clause. opencc-js: MIT and Apache-2.0 (OpenCC data).\n`;
const dir = path.join(__dirname, '../src/memory/speech/data');
const write = (file, what, name, obj) =>
  fs.writeFileSync(
    path.join(dir, file),
    header(what) + `export const ${name}: Readonly<Record<string, string>> = ${JSON.stringify(obj, null, 0).replace(/","/g, '",\n"').replace(/^\{/, '{\n').replace(/\}$/, ',\n}')};\n`,
  );
write('t2s.ts', 'Traditional -> simplified, one code point to one code point.', 'T2S', t2s);
write('mandarin.ts', 'Toneless pinyin -> the simplified characters read that way.', 'MANDARIN_READINGS', mandarin);
write('cantonese.ts', 'Toneless jyutping -> the simplified characters read that way.', 'CANTONESE_READINGS', cantonese);
console.log({ chars: set.size, t2s: Object.keys(t2s).length, mandarin: Object.keys(mandarin).length, cantonese: Object.keys(cantonese).length });
